import esbuild from 'esbuild';
import process from 'process';
import builtins from 'builtin-modules';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, visit the plugin's github repository.
*/
`;

const production = process.argv.includes('--production');

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtins,
	],
	// IS_DEV drives the sync-interval floor: 1 minute in a dev build, 5 in production.
	// esbuild substitutes this textually at bundle time; src/global.d.ts carries the
	// ambient declaration the type checker needs.
	define: { IS_DEV: JSON.stringify(!production) },
	format: 'cjs',
	target: 'es2018',
	logLevel: 'info',
	sourcemap: production ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: production,
	platform: 'browser',
});

if (production) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
